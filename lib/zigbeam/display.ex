  @compile {:no_warn_undefined, [:zigbeam_i2c]}

  @doc "Open, init and draw a test frame in the caller; returns each step's result (for remote debugging)."
  def probe do
    init = step(fn -> command(@init) end)
    frame = step(fn -> render(["zigbeam probe", "hello from erpc"]) end)
    [init: init, render: frame, alive: Process.whereis(:display)]
  end

  defp step(fun) do
    try do
      fun.()
    catch
      kind, reason -> {:caught, kind, reason}
    end
  end

  @doc "Start the display process (registered as `:display`). Never fails; without a panel it just drops frames."
  def start do
    pid = spawn(fn -> init() end)
    Process.register(pid, :display)
    {:ok, pid}
  end

  @doc "Show up to 8 lines of text (strings or charlists); longer lines are cut at 21 chars."
  def show(lines) when is_list(lines) do
    case Process.whereis(:display) do
      nil -> {:error, :not_started}
      pid -> send(pid, {:show, lines}); :ok
    end
  end

  defp init, do: init(3)

  defp init(attempts) do
    case step(fn -> command(@init) end) do
      {:error, :nack} when attempts > 1 ->
        :timer.sleep(200)
        init(attempts - 1)

      :ok ->
        IO.puts("display: ssd1306 up on sda #{@sda} scl #{@scl}")
        render([])
        loop(true)

      error ->
        IO.puts("display: not available: #{inspect(error)}")
        loop(false)
    end
  end

  defp loop(present?) do
    receive do
      {:show, lines} ->
        if present?, do: render(lines)
        loop(present?)

      _ ->
        loop(present?)
    end
  end

  # AtomVM's Elixir library lacks Enum.take/with_index and to_charlist, so
  # this sticks to :lists and :erlang.
  defp render(lines) do
    padded = :lists.sublist(lines ++ List.duplicate("", @pages), @pages)

    :lists.zip(:lists.seq(0, @pages - 1), padded)
    |> Enum.each(fn {page, line} ->
      command([0x21, 0, 127, 0x22, page, page])
      write([0x40 | page_bytes(line)])
    end)
  end

  defp command(cmds), do: write([0x00 | cmds])

  # Bit-banged I2C NIF from firmware/components/atomvm_zigbee/zigbeam_i2c.c:
  # ESP-IDF's I2C driver cannot be installed next to the Zigbee stack on the C6.
  defp write(bytes), do: :zigbeam_i2c.write(@sda, @scl, @addr, :erlang.list_to_binary(bytes))

  defp page_bytes(line) do
    chars = :lists.sublist(chars(line), @cols)

    glyphs = Enum.flat_map(chars, &glyph/1)
    glyphs ++ List.duplicate(0, 128 - length(glyphs))
  end

  defp chars(line) when is_binary(line), do: :erlang.binary_to_list(line)
  defp chars(line) when is_list(line), do: line
  defp chars(line) when is_atom(line), do: :erlang.atom_to_list(line)
  defp chars(line) when is_integer(line), do: :erlang.integer_to_list(line)

  defp glyph(c) when c >= 32 and c <= 126 do
    :erlang.binary_to_list(:binary.part(@font, (c - 32) * 5, 5)) ++ [0]
  end

  defp glyph(_), do: [0x7F, 0x41, 0x41, 0x41, 0x7F, 0]
end
